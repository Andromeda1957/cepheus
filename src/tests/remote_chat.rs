    let reader = ["python3", "-I", script];
    let before = std::fs::read(&db).unwrap();
    let (items, seen) = opencode_items(&reader, &db, id).expect("read");
    assert_eq!(std::fs::read(&db).unwrap(), before, "read only");
    assert_eq!(seen, ModelSeen { model: Some("kimi-k2".into()), effort: Some("high".into()) });
    assert!(matches!(&items[0], Item::User { text, .. } if text == "hello"));
    assert_eq!(items[1], Item::Thinking { text: "think".into() });
