#[test]
fn answered_question_state_survives_incremental_reads_and_reopen() {
    let dir = crate::testsupport::TempDir::new("answered-questions");
    let path = dir.path().join("rollout.jsonl");
    let question = codex_item(json!({"type":"AgentMessage","id":"ask-1",
    "content":[{"type":"Text","text":"Choose"}],
    "questions":[
        {"title":"First?","options":["Yes","No"]},
        {"title":"Second?","options":["Yes","No"]},
        {"title":"Third?","options":["Yes","No"]}
    ]}));
    let mut data = format!("{question}\n");
    std::fs::write(&path, &data).unwrap();
    let mut log = Log::new(Source::Codex(path.clone()));
    log.read_file(&path);
    let quoted = format!(
        "Please debug this example: <send_user_message_question_reply>{}</send_user_message_question_reply>",
        json!([{"question":"Third?","answer":"Yes","questionItemId":json!(["request_user_input_async","ask-1",2]).to_string()}])
    );
    let quoted =
        codex_item(json!({"type":"UserMessage","id":"quoted-example", "content":[{"type":"Text","text":quoted}]}));
    data.push_str(&format!("{quoted}\n"));
    std::fs::write(&path, &data).unwrap();
    log.read_file(&path);
    assert_eq!(
        serde_json::to_value(&log.items).unwrap()[0]["questions"][2]["answered"],
        false,
        "quoted examples do not complete a question"
    );
    for (round, index) in [2, 0, 1].into_iter().enumerate() {
        let before = log.generation;
        let reply = format!(
            "<send_user_message_question_reply>{}</send_user_message_question_reply>",
            json!([{"question":format!("Question {index}?"),"answer":"Yes","questionItemId":json!(["request_user_input_async","ask-1",index]).to_string()}])
        );
        let record = codex_item(json!({"type":"UserMessage","id":format!("reply-{index}"),
            "content":[{"type":"Text","text":reply}]}));
        data.push_str(&format!("{record}\n"));
        std::fs::write(&path, &data).unwrap();
        log.read_file(&path);
        let wire = serde_json::to_value(&log.items).unwrap();
        assert_eq!(wire[0]["questions"][index]["answered"], true);
        assert!(log.generation > before, "existing phone cards need a replacement push");
        assert_eq!(
            wire[0]["questions"].as_array().unwrap().iter().filter(|q| q["answered"] == true).count(),
            round + 1
        );
    }
    let mut reopened = Log::new(Source::Codex(path.clone()));
    reopened.read_file(&path);
    assert_eq!(reopened.items, log.items, "answered choices must survive a gateway restart");
}

#[test]
fn unresolved_questions_outlive_history_limits_and_rebuild_from_the_whole_log() {
    use std::io::Write;
    let dir = crate::testsupport::TempDir::new("durable-questions");
    let path = dir.path().join("rollout.jsonl");
    let question = codex_item(json!({"type":"AgentMessage","id":"old",
        "content":[{"type":"Text","text":"Choose"}],
        "questions":[{"title":"First?","options":["Yes","No"]},{"title":"Second?","options":["Yes","No"]}]}));
    let receipt = |index| {
        codex_item(json!({"type":"UserMessage","id":"reply",
        "content":[{"type":"Text","text":format!("<send_user_message_question_reply>{}</send_user_message_question_reply>",
            json!([{"question":"First?","answer":"Yes","questionItemId":json!(["request_user_input_async","old",index]).to_string()}]))}]}))
    };
    let quoted = codex_item(json!({"type":"UserMessage","id":"example",
        "content":[{"type":"Text","text":format!("Example: {}", receipt(1)["payload"]["item"]["content"][0]["text"].as_str().unwrap())}]}));
    let mut file = fs::File::create(&path).unwrap();
    writeln!(file, "{question}").unwrap();
    writeln!(file, "{}", receipt(0)).unwrap();
    let mut log = Log::new(Source::Codex(path.clone()));
    log.read_file(&path);
    // Ordinary history still has its usual item and byte budgets. A pending
    // question and its older answer receipt must survive both boundaries.
    let filler = codex_item(json!({"type":"AgentMessage","id":"filler",
        "content":[{"type":"Text","text":"x".repeat(8_000)}]}));
    for _ in 0..3_300 {
        writeln!(file, "{filler}").unwrap();
    }
    writeln!(file, "{quoted}").unwrap();
    file.flush().unwrap();
    while log.offset < fs::metadata(&path).unwrap().len() {
        log.read_file(&path);
    }
    assert_eq!(log.items.len(), ITEMS_MAX);
    assert!(log.dropped > 0);
    assert_eq!(log.questions.iter().map(|q| q.id.as_str()).collect::<Vec<_>>(), ["old:1"]);
    let original_offset = log.offset;
    let original_total = log.total();
    assert_eq!(super::super::questionpick::by_id(&log.questions, "old:1").unwrap().options, ["Yes", "No"]);
    let mut reopened = Log::new(Source::Codex(path.clone()));
    reopened.read_file(&path);
    assert_eq!(
        reopened.questions, log.questions,
        "cold tail reads hydrate questions and receipts from the skipped prefix"
    );
    assert!(reopened.items.len() <= ITEMS_MAX);
    assert!(!reopened.items.iter().any(|i| matches!(i, Item::Assistant { questions, .. } if !questions.is_empty())));
    assert_eq!(reopened.offset, original_offset, "question hydration never changes byte offsets");

    // The wire carries the full question snapshot even with no ordinary
    // rows, and a conversation reset removes it independently of rows.
    let chunk = Chunk {
        kind: ChunkKind::Log,
        generation: 7,
        dropped: original_total,
        start: original_total,
        items: Vec::new(),
        seen: ModelSeen::default(),
        questions: Some(reopened.questions.clone()),
        question_replies: reopened.question_replies.clone(),
    };
    let chunk = serde_json::from_value(serde_json::to_value(&chunk).unwrap()).unwrap();
    let mut hub = Cache::default();
    assert_eq!(hub.apply(8, chunk).unwrap().questions, log.questions);
    assert!(hub.peek(8).unwrap().question_answered("old:0"));
    for id in 9..=17 {
        hub.apply(id, Chunk::of(ChunkKind::Screen));
    }
    assert!(hub.peek(8).is_none(), "the small chat cache really evicted this conversation");
    // Reopening an evicted local conversation uses the same cold read path.
    let mut reopened = Log::new(Source::Codex(path.clone()));
    reopened.read_file(&path);
    assert_eq!(reopened.questions, log.questions);

    let answer = format!("{}\n", receipt(1));
    // A partially written native answer never resolves the remaining card.
    file.write_all(answer[..answer.len() / 2].as_bytes()).unwrap();
    file.flush().unwrap();
    reopened.read_file(&path);
    assert_eq!(reopened.questions.len(), 1);
    file.write_all(answer[answer.len() / 2..].as_bytes()).unwrap();
    file.flush().unwrap();
    reopened.read_file(&path);
    assert!(reopened.questions.is_empty());
    assert!(reopened.question_replies.contains(&String::from("old:1")));
    let mut cold = Log::new(Source::Codex(path.clone()));
    cold.read_file(&path);
    assert!(cold.questions.is_empty(), "an old answer receipt is authoritative after restart too");
    assert!(cold.question_replies.contains(&String::from("old:1")));
    let next = Chunk {
        kind: ChunkKind::Log,
        generation: 8,
        dropped: original_total,
        start: original_total,
        items: Vec::new(),
        seen: ModelSeen::default(),
        questions: Some(Vec::new()),
        question_replies: cold.question_replies.clone(),
    };
    assert!(hub.apply(8, next).unwrap().questions.is_empty());
    assert!(hub.peek(8).unwrap().question_answered("old:1"));

    // Truncation/replacement at the same path must not leak an old question.
    fs::write(&path, format!("{question}\n")).unwrap();
    reopened.read_file(&path);
    assert_eq!(reopened.questions.len(), 2);
    fs::write(
        &path,
        format!(
            "{}\n",
            codex_item(json!({"type":"AgentMessage","id":"fresh",
        "content":[{"type":"Text","text":"New conversation"}]}))
        ),
    )
    .unwrap();
    reopened.read_file(&path);
    assert!(reopened.questions.is_empty());
    assert!(!reopened.question_answered("old:1"), "reset is not an answer receipt");
    let replacement = dir.path().join("replacement.jsonl");
    fs::write(&replacement, format!("{question}\n{question}\n")).unwrap();
    fs::rename(&replacement, &path).unwrap();
    reopened.read_file(&path);
    assert_eq!(reopened.questions.len(), 2, "replacement resets question identity and deduplicates records");
    let mut remote = Cache::default();
    let pending = Chunk {
        kind: ChunkKind::Log,
        generation: 9,
        dropped: 3_000,
        start: 3_000,
        items: Vec::new(),
        seen: ModelSeen::default(),
        questions: Some(reopened.questions.clone()),
        question_replies: Vec::new(),
    };
    assert_eq!(remote.apply(9, pending).unwrap().questions.len(), 2);
    assert!(
        remote.apply(9, Chunk::of(ChunkKind::Screen)).unwrap().questions.is_empty(),
        "a new source cannot inherit a previous conversation's cards"
    );
}
