/// A copy read afresh never shares a generation with an earlier one: a
/// restarted gateway or an evicted chat reads a long log from another item
/// (`READ_MAX`), and a phone that joined pages of equal generations spliced
/// the two reads (owner, 2026-11-08: "Messages must not appear and
/// disappear").
#[test]
fn a_chat_read_afresh_never_reuses_a_generation() {
    let dir = crate::testsupport::TempDir::new("chat-afresh");
    let dirs = Dirs {
        claude: dir.path().join("claude"),
        codex: dir.path().join("codex"),
        opencode_db: dir.path().join("opencode.db"),
        antigravity: dir.path().join("antigravity"),
        start_dir: dir.path().join("repo"),
        sqlite3: Vec::new(),
    };
    let id = "11111111-1111-4111-8111-111111111111";
    let path = crate::claude::transcript_path(&dirs.claude, &dirs.start_dir.to_string_lossy(), id);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(&path, format!("{}\n{}\n", user(json!("one")), user(json!("two")))).unwrap();
    let mut info = crate::tui::tests::session(4, Tool::Claude, crate::protocol::Status::Idle, true);
    info.conversation = Some(id.into());

    let mut before = Cache::default();
    let first = before.get(&info, &dirs).expect("the chat").generation;
    let mut restarted = Cache::default();
    let second = restarted.get(&info, &dirs).expect("the chat read again").generation;
    assert_ne!(first, second, "a phone holding the first read must replace it");

    // A hub holding a host's copy gets the restarted host's whole copy,
    // not items after the indexes of the read the host no longer has.
    let mut hub = Cache::default();
    let hub_id = crate::protocol::host_id(1, 4);
    hub.apply(hub_id, before.chunk(&info, &dirs, 0, 0));
    let (from, generation) = hub.peek(hub_id).map(|l| (l.total(), l.generation)).unwrap();
    assert_eq!((from, generation), (2, first));
    let chunk = restarted.chunk(&info, &dirs, from, generation);
    assert_eq!((chunk.start, chunk.items.len(), chunk.generation), (0, 2, second));
}

