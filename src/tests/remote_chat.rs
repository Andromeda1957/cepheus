fn claude(records: &[Value]) -> Vec<Item> {
    let mut out = Vec::new();
    let mut seen = ModelSeen::default();
    for r in records {
        claude_record(r, None, &mut out, &mut seen);
    }
    out
}

fn user(content: Value) -> Value {
    json!({"type": "user", "timestamp": "2026-10-27T10:00:00Z", "message": {"role": "user", "content": content}})
}

