fn images_of(item: &Item) -> (&str, Vec<&str>) {
    match item {
        Item::User { text, images, .. } => (text.as_str(), images.iter().map(String::as_str).collect()),
        other => panic!("not the owner's message: {other:?}"),
    }
}

/// Owner, 2026-11-03: the screenshots he sent showed as "[image]" where the
/// Claude app shows them. Each image is named by its record's place in the
/// log and its place in that record, for the phone to fetch.
#[test]
fn images_the_owner_sent_are_named_for_the_phone_to_fetch() {
    let mut out = Vec::new();
    let mut seen = ModelSeen::default();
    let mut read = |v: Value, offset: Option<u64>| claude_record(&v, offset, &mut out, &mut seen);
    read(
        user(json!([{"type": "text", "text": "look"}, img("image/png", "AAAA"), img("image/jpeg", "BBBB")])),
        Some(100),
    );
    // A screenshot a tool took is the tool's, not the owner's.
    read(user(json!([{"type": "tool_result", "tool_use_id": "t1", "content": [img("image/png", "CCCC")]}])), Some(200));
    // Sent while a turn ran: with words, and alone.
    read(queued(json!([{"type": "text", "text": "and these"}, img("image/png", "DDDD")])), Some(300));
    read(queued(json!([img("image/png", "EEEE")])), Some(400));
    // A search reads without places and names none.
    read(user(json!([img("image/png", "FFFF")])), None);
    assert_eq!(out.len(), 4, "{out:?}");
    assert_eq!(images_of(&out[0]), ("look", vec!["100.0", "100.1"]));
    assert!(matches!(&out[1], Item::Result { call, .. } if call == "t1"));
    assert_eq!(images_of(&out[2]), ("and these", vec!["300.0"]));
    assert_eq!(images_of(&out[3]), ("", vec!["400.0"]));
}

#[test]
fn an_image_is_read_again_from_its_record_in_the_log() {
    let dir = crate::testsupport::TempDir::new("chat-images");
    let path = dir.path().join("t.jsonl");
    let first = format!("{}\n", user(json!("hello")));
    let tool = json!({"type": "tool_result", "tool_use_id": "t1", "content": [img("image/png", "TOOL")]});
    let second = format!("{}\n", user(json!([tool, {"type": "text", "text": "see"}, img("image/jpeg", "/9j/AAAA")])));
    std::fs::write(&path, format!("{first}{second}")).unwrap();
    let mut log = Log::new(Source::Claude(path.clone()));
    log.read_file(&path);
    let key = match log.items.iter().find(|i| matches!(i, Item::User { text, .. } if text == "see")) {
        Some(Item::User { images, .. }) => images.clone(),
        other => panic!("{other:?}"),
    };
    // The tool's screenshot comes first in the record, so the owner's is its second image.
    assert_eq!(key, vec![format!("{}.1", first.len())]);
    assert_eq!(log.source.image(&key[0]).unwrap(), ("image/jpeg".to_string(), "/9j/AAAA".to_string()));
    assert!(log.source.image("0.0").is_err(), "the first record holds no image");
    assert!(log.source.image("not a key").is_err());
    assert!(Source::Screen.image(&key[0]).is_err());
}

