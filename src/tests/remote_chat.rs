/// A session on another host: its host reads the log and the hub keeps a
/// copy, sent only what it lacks, with the host's indexes and generations.
#[test]
fn a_hubs_copy_of_a_hosts_chat_gets_only_what_it_lacks_and_follows_a_new_chat() {
    let dir = crate::testsupport::TempDir::new("chat-chunks");
    let dirs = Dirs {
        claude: dir.path().join("claude"),
        codex: dir.path().join("codex"),
        opencode_db: dir.path().join("opencode.db"),
        antigravity: dir.path().join("antigravity"),
        start_dir: dir.path().join("repo"),
        sqlite3: Vec::new(),
    };
    let first = "11111111-1111-4111-8111-111111111111";
    let path = crate::claude::transcript_path(&dirs.claude, &dirs.start_dir.to_string_lossy(), first);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(&path, format!("{}\n{}\n", user(json!("one")), user(json!("two")))).unwrap();
    let mut info = crate::tui::tests::session(3, Tool::Claude, crate::protocol::Status::Idle, true);
    info.conversation = Some(first.into());
    let (mut host, mut hub) = (Cache::default(), Cache::default());
    let hub_id = crate::protocol::host_id(1, 3);
    let texts = |log: &Log| -> Vec<String> {
        log.items
            .iter()
            .map(|i| match i {
                Item::User { text, .. } => text.clone(),
                other => format!("{other:?}"),
            })
            .collect()
    };
    // What a host sends survives the wire.
    let roundtrip = |c: Chunk| -> Chunk { serde_json::from_value(serde_json::to_value(&c).unwrap()).unwrap() };

    let sync = |host: &mut Cache, hub: &mut Cache, info: &crate::protocol::SessionInfo| -> Chunk {
        let (from, generation) = hub.peek(hub_id).map_or((0, 0), |l| (l.total(), l.generation));
        let chunk = roundtrip(host.chunk(info, &dirs, from, generation));
        hub.apply(hub_id, chunk.clone());
        chunk
    };
    let chunk = sync(&mut host, &mut hub, &info);
    assert_eq!((chunk.start, chunk.items.len()), (0, 2));
    assert_eq!(texts(hub.peek(hub_id).unwrap()), ["one", "two"]);

    let chunk = sync(&mut host, &mut hub, &info);
    assert!(chunk.items.is_empty(), "nothing new: nothing sent");

    std::thread::sleep(std::time::Duration::from_millis(750));
    std::fs::write(&path, format!("{}\n{}\n{}\n", user(json!("one")), user(json!("two")), user(json!("three"))))
        .unwrap();
    let chunk = sync(&mut host, &mut hub, &info);
    assert_eq!((chunk.start, chunk.items.len()), (2, 1), "only the new item travels");
    assert_eq!(texts(hub.peek(hub_id).unwrap()), ["one", "two", "three"]);

    // `/clear`: a new conversation replaces the copy, under a new generation.
    let generation = hub.peek(hub_id).unwrap().generation;
    let second = "22222222-2222-4222-8222-222222222222";
    let path = crate::claude::transcript_path(&dirs.claude, &dirs.start_dir.to_string_lossy(), second);
    std::fs::write(&path, format!("{}\n", user(json!("fresh")))).unwrap();
    info.conversation = Some(second.into());
    sync(&mut host, &mut hub, &info);
    let log = hub.peek(hub_id).unwrap();
    assert_eq!(texts(log), ["fresh"]);
    assert_ne!(log.generation, generation, "the phone replaces what it shows");

    // A program whose screen is its chat, and a host with no log for it.
    assert_eq!(hub.apply(hub_id, Chunk::of(ChunkKind::Screen)).map(|l| l.source.clone()), Some(Source::Screen));
    assert!(hub.apply(hub_id, Chunk::of(ChunkKind::None)).is_none());
    assert!(hub.peek(hub_id).is_none());
}

