/// What a session whose turn a service stop cut short is told once it is
/// running again.
pub const RESUME_MESSAGE: &str =
    "Cepheus's service restarted while you were working, which interrupted your turn. Continue where you left off.";

impl Config {
    pub fn plugin_enabled(&self, id: &str) -> bool {
        crate::extensions::enabled(&self.plugins, id)
    }

    /// Load the configuration file, falling back to defaults when it is absent.
    pub fn load() -> (Config, Option<String>) {
        Self::load_from(&paths::config_path())
    }

    /// The config file, which may have comments, with the hosts from the
    /// hosts file beside it (`hosts_path`) once there is one.
    pub fn load_from(path: &Path) -> (Config, Option<String>) {
        let machine = read_hosts_file(path);
        let parsed = match fs::read(path) {
            Ok(bytes) => serde_json::from_slice::<serde_json::Value>(&strip_comments(&bytes))
                .map_err(|err| format!("{}: {err}", path.display())),
            Err(_) => Ok(serde_json::Value::Object(serde_json::Map::new())),
        };
        let parsed = parsed.and_then(|value| crate::profile::merge(path, value).map_err(|e| format!("{e:#}")));
        let (mut cfg, err) = match parsed {
            Ok(mut value) => {
                // What `peer setup` recorded fills in what the owner's file
                // leaves out.
                if let (serde_json::Value::Object(map), Some(file)) = (&mut value, &machine) {
                    for (key, setting) in &file.settings {
                        map.entry(key.clone()).or_insert_with(|| setting.clone());
                    }
                }
                match serde_json::from_value::<Config>(value) {
                    Ok(cfg) => (cfg, None),
                    Err(err) => (Config::default(), Some(format!("{}: {err}", path.display()))),
                }
            }
            Err(err) => (Config::default(), Some(err)),
        };
        if hosts_path(path).exists() {
            cfg.hosts = machine.map(|f| f.hosts).unwrap_or_default();
        }
        let mut err = err;
        if let Err(problem) = cfg.attention.validate() {
            cfg.attention = crate::attention::Settings::default();
            err = Some(format!("attention settings: {problem:#}"));
        }
        if let Err(problem) = crate::providers::load_manifests(path, &mut cfg.providers)
            .and_then(|()| crate::providers::install(&cfg.providers))
        {
            cfg.providers.clear();
            let _ = crate::providers::install(&[]);
            err = Some(match err {
                Some(err) => format!("{err}; providers: {problem:#}"),
                None => format!("providers: {problem:#}"),
            });
        }
        crate::providers::configure_plugins(&cfg.plugins);
        (cfg.sanitized(), err)
    }

    /// Where Codex Security scans are kept.
    pub fn scans_dir(&self) -> PathBuf {
        self.scans_dir.clone().unwrap_or_else(|| paths::data_dir().join("security-scans"))
    }

    /// The scratch terminal's program: the configured one, else the owner's login shell as the account database
    /// records it, else `$SHELL`, else `/bin/sh`. It runs on the deck's terminal, so it is interactive and
    /// reads its rc files, oh-my-zsh included, as it does in a new kitty window. A service started by systemd
    /// may have no `$SHELL`, so the account's shell comes first.
    pub fn shell(&self) -> Vec<String> {
        if !self.shell_command.is_empty() {
            return self.shell_command.clone();
        }
        let shell = login_shell()
            .or_else(|| std::env::var("SHELL").ok().filter(|s| !s.trim().is_empty()))
            .unwrap_or_else(|| "/bin/sh".into());
        vec![shell]
    }

    fn sanitized(mut self) -> Self {
        self.startup = self.startup.sanitized();
        let defaults = Config::default();
        if self.claude_command.is_empty() {
            self.claude_command = defaults.claude_command;
        }
        if self.codex_command.is_empty() {
            self.codex_command = defaults.codex_command;
        }
        if self.antigravity_command.is_empty() {
            self.antigravity_command = defaults.antigravity_command;
        }
        if self.grok_command.is_empty() {
            self.grok_command = defaults.grok_command;
        }
        if self.opencode_command.is_empty() {
            self.opencode_command = defaults.opencode_command;
        }
        self.scrollback = self.scrollback.clamp(100, 200_000);
        self.sidebar_width = self.sidebar_width.clamp(24, 60);
        if self.remote_listen.trim().is_empty() {
            self.remote_listen = defaults.remote_listen;
        }
        // A host the deck cannot name, number or verify is left out, and so
        // is a second one with the same name or tag.
        let mut names = std::collections::HashSet::new();
        let mut tags = std::collections::HashSet::new();
        self.hosts.retain(|h| {
            valid_host_name(&h.name)
                && (1..=crate::protocol::MAX_HOST_TAG).contains(&h.tag)
                && !h.addresses.is_empty()
                && h.fingerprint.len() == 64
                && h.fingerprint.bytes().all(|b| b.is_ascii_hexdigit())
                && names.insert(h.name.clone())
                && tags.insert(h.tag)
        });
        self.host_name = self.host_name.take().map(|n| n.trim().to_string()).filter(|n| !n.is_empty());
        self.ask.timeout = self.ask.timeout.clamp(10, 1800);
        self.program_restart_check_secs = self.program_restart_check_secs.clamp(1, 3600);
        self.program_restart_grace_secs = self.program_restart_grace_secs.min(3600);
        self
    }

    /// This machine's heading on the deck.
    pub fn local_host_label(&self) -> String {
        self.host_name.clone().unwrap_or_else(|| {
            let name = crate::util::hostname();
            let mut chars = name.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().chain(chars).collect(),
                None => "This machine".to_string(),
            }
        })
    }

    pub fn resolve_start_dir(&self) -> Result<PathBuf> {
        let explicit = self.start_dir.clone().or_else(|| crate::paths::env_var(START_DIR_SUFFIX).map(PathBuf::from));
        let searched: Vec<PathBuf> = std::env::current_dir().into_iter().collect();
        start_dir_from(explicit, &searched)
    }
}

/// This user's login shell from the account database (`getpwuid_r`), when
/// it is an executable file.
pub fn login_shell() -> Option<String> {
    let mut buf = vec![0 as libc::c_char; 16 * 1024];
    // SAFETY: an all-zero passwd is a valid value for getpwuid_r to fill.
    let mut pw: libc::passwd = unsafe { std::mem::zeroed() };
    let mut out: *mut libc::passwd = std::ptr::null_mut();
    // SAFETY: every pointer is valid for the call and `buf` outlives the
    // strings it fills in, which are copied out before it is dropped.
    let rc = unsafe { libc::getpwuid_r(libc::getuid(), &mut pw, buf.as_mut_ptr(), buf.len(), &mut out) };
    if rc != 0 || out.is_null() || pw.pw_shell.is_null() {
        return None;
    }
    // SAFETY: getpwuid_r succeeded, so pw_shell points at a NUL-terminated
    // string inside `buf`.
    let shell = unsafe { std::ffi::CStr::from_ptr(pw.pw_shell) }.to_string_lossy().into_owned();
    let path = Path::new(&shell);
    let usable = path.is_absolute()
        && fs::metadata(path)
            .is_ok_and(|m| m.is_file() && std::os::unix::fs::PermissionsExt::mode(&m.permissions()) & 0o111 != 0);
    usable.then_some(shell)
}

/// Set by the deck when it starts the service, so the service starts sessions
/// where the deck resolved them rather than from its own home-directory cwd.
/// A service from before the rename hands over with the old name set.
pub const START_DIR_ENV: &str = "CEPHEUS_START_DIR";
pub const START_DIR_SUFFIX: &str = "START_DIR";

/// An explicit start directory, else the primary checkout of the first of
/// `searched` inside a repository. There is no fallback directory: review
/// CR-20261026-30a93f39b2 found installed builds silently starting every
/// session in the home directory once their build worktree was removed.
pub fn start_dir_from(explicit: Option<PathBuf>, searched: &[PathBuf]) -> Result<PathBuf> {
    if let Some(dir) = explicit {
        return Ok(dir);
    }
    searched.iter().find_map(|dir| primary_checkout(dir)).with_context(|| {
        format!(
            "cannot find the repository to start sessions in; set \"start_dir\" in {}",
            paths::config_path().display()
        )
    })
}

/// The main worktree of the Git repository containing `dir`.
pub fn primary_checkout(dir: &Path) -> Option<PathBuf> {
    if !dir.is_dir() {
        return None;
    }
    let out = Command::new("git")
        .arg("-C")
        .arg(dir)
        .args(["rev-parse", "--path-format=absolute", "--git-common-dir"])
        .stdin(Stdio::null())
        .stderr(Stdio::null())
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    let common = PathBuf::from(String::from_utf8(out.stdout).ok()?.trim());
    if common.file_name()? == ".git" {
        common.parent().map(Path::to_path_buf)
    } else {
        None
    }
}

pub type Rgb8 = (u8, u8, u8);

/// Number of palette slots alacritty_terminal addresses (16 named, 240
/// indexed, then foreground, background, cursor, dim and bright variants).
pub const PALETTE_LEN: usize = 269;

#[derive(Debug, Clone)]
pub struct Palette {
    pub colors: Vec<Rgb8>,
}

const XTERM16: [Rgb8; 16] = [
    (0x00, 0x00, 0x00),
    (0xcd, 0x00, 0x00),
    (0x00, 0xcd, 0x00),
    (0xcd, 0xcd, 0x00),
    (0x00, 0x00, 0xee),
    (0xcd, 0x00, 0xcd),
    (0x00, 0xcd, 0xcd),
    (0xe5, 0xe5, 0xe5),
    (0x7f, 0x7f, 0x7f),
    (0xff, 0x00, 0x00),
    (0x00, 0xff, 0x00),
    (0xff, 0xff, 0x00),
    (0x5c, 0x5c, 0xff),
    (0xff, 0x00, 0xff),
    (0x00, 0xff, 0xff),
    (0xff, 0xff, 0xff),
];

fn dim(c: Rgb8) -> Rgb8 {
    let f = |v: u8| ((u16::from(v) * 2) / 3) as u8;
    (f(c.0), f(c.1), f(c.2))
}

impl Palette {
    pub fn from_parts(base16: [Rgb8; 16], fg: Rgb8, bg: Rgb8, cursor: Option<Rgb8>) -> Self {
        let mut colors = vec![(0, 0, 0); PALETTE_LEN];
        colors[..16].copy_from_slice(&base16);
        const LEVELS: [u8; 6] = [0, 95, 135, 175, 215, 255];
        for i in 0..216 {
            colors[16 + i] = (LEVELS[i / 36], LEVELS[(i / 6) % 6], LEVELS[i % 6]);
        }
        for i in 0..24 {
            let v = 8 + 10 * i as u8;
            colors[232 + i] = (v, v, v);
        }
        colors[256] = fg;
        colors[257] = bg;
        colors[258] = cursor.unwrap_or(fg);
        for i in 0..8 {
            colors[259 + i] = dim(base16[i]);
        }
        colors[267] = fg;
        colors[268] = dim(fg);
        Palette { colors }
    }

    pub fn get(&self, index: usize) -> Rgb8 {
        self.colors.get(index).copied().unwrap_or((0, 0, 0))
    }

    /// Load from a kitty-format colour file, following `include` lines.
    pub fn load(cfg: &Config) -> Palette {
        let path = cfg.palette_file.clone().unwrap_or_else(|| paths::home().join(".config/kitty/kitty.conf"));
        let mut entries = Vec::new();
        collect_kitty(&path, 0, &mut entries);
        Self::from_kitty_entries(&entries)
    }

    pub fn from_kitty_entries(entries: &[(String, String)]) -> Palette {
        let mut base = XTERM16;
        let mut fg = (0xdd, 0xdd, 0xdd);
        let mut bg = (0x00, 0x00, 0x00);
        let mut cursor = None;
        for (key, value) in entries {
            let Some(rgb) = parse_hex(value) else { continue };
            match key.as_str() {
                "foreground" => fg = rgb,
                "background" => bg = rgb,
                "cursor" => cursor = Some(rgb),
                k => {
                    if let Some(n) = k.strip_prefix("color").and_then(|n| n.parse::<usize>().ok()) {
                        if n < 16 {
                            base[n] = rgb;
                        }
                    }
                }
            }
        }
        Palette::from_parts(base, fg, bg, cursor)
    }
}

fn collect_kitty(path: &Path, depth: usize, out: &mut Vec<(String, String)>) {
    if depth > 6 {
        return;
    }
    let Ok(text) = fs::read_to_string(path) else { return };
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let mut parts = line.splitn(2, char::is_whitespace);
        let key = parts.next().unwrap_or("");
        let value = parts.next().unwrap_or("").trim();
        if key == "include" {
            let target = if let Some(rest) = value.strip_prefix("~/") {
                paths::home().join(rest)
            } else {
                let p = PathBuf::from(value);
                if p.is_absolute() {
                    p
                } else {
                    path.parent().unwrap_or_else(|| Path::new("/")).join(p)
                }
            };
            collect_kitty(&target, depth + 1, out);
        } else {
            out.push((key.to_string(), value.to_string()));
        }
    }
}

pub fn parse_hex(value: &str) -> Option<Rgb8> {
    let hex = value.trim().strip_prefix('#')?;
    let digits: Vec<u8> = hex.chars().map(|c| c.to_digit(16).map(|d| d as u8)).collect::<Option<_>>()?;
    match digits.len() {
        3 => Some((digits[0] * 17, digits[1] * 17, digits[2] * 17)),
        6 => Some((digits[0] * 16 + digits[1], digits[2] * 16 + digits[3], digits[4] * 16 + digits[5])),
        _ => None,
    }
}

