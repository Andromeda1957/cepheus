/// One selection shared by merge refresh and the native authenticated updater.
#[derive(Debug, Clone, PartialEq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct RefreshPolicy {
    pub build_host: String,
    pub hosts: Vec<String>,
    pub excluded_hosts: Vec<String>,
}

impl RefreshPolicy {
    pub fn valid(&self) -> bool {
        let names: Vec<_> = self.hosts.iter().chain(&self.excluded_hosts).collect();
        !self.hosts.is_empty()
            && self.hosts.len() <= 64
            && self.excluded_hosts.len() <= 64
            && names.iter().all(|name| valid_host_name(name) && name.as_str() != "auto")
            && names.iter().collect::<std::collections::BTreeSet<_>>().len() == names.len()
            && self.hosts.contains(&self.build_host)
    }

    pub fn allows(&self, host: &str) -> bool {
        self.valid()
            && self.hosts.iter().any(|name| name == host)
            && !self.excluded_hosts.iter().any(|name| name == host)
    }
}

