/// The hosts file beside `config`: written by `cepheus hosts install` and `remove`, so nothing the deck writes
/// touches the owner's own config file, as Neovim's plugin manager keeps its lock file apart from `init.lua`.
pub fn hosts_path(config: &Path) -> PathBuf {
    config.with_file_name("hosts.json")
}

/// What the hosts file holds: the hosts a hub drives, and on a host the
/// settings `peer setup` made (its listener, its name), which the config
/// file overrides key by key.
#[derive(Debug, Clone, Default, PartialEq, Deserialize, Serialize)]
pub struct HostsFile {
    #[serde(default)]
    pub hosts: Vec<HostConfig>,
    #[serde(default, skip_serializing_if = "serde_json::Map::is_empty")]
    pub settings: serde_json::Map<String, serde_json::Value>,
}

/// The hosts file beside `config`, empty when there is none or it does not
/// read.
pub fn read_hosts_file(config: &Path) -> Option<HostsFile> {
    let bytes = fs::read(hosts_path(config)).ok()?;
    serde_json::from_slice::<HostsFile>(&strip_comments(&bytes)).ok()
}

/// The hosts recorded beside `config`: the hosts file once there is one,
/// else the `hosts` an older build wrote into the config file itself.
pub fn read_hosts(config: &Path) -> Vec<HostConfig> {
    if hosts_path(config).exists() {
        return read_hosts_file(config).map(|f| f.hosts).unwrap_or_default();
    }
    fs::read(config)
        .ok()
        .and_then(|bytes| serde_json::from_slice::<serde_json::Value>(&strip_comments(&bytes)).ok())
        .and_then(|v| v.get("hosts").cloned())
        .and_then(|h| serde_json::from_value(h).ok())
        .unwrap_or_default()
}

/// Record `hosts` in the hosts file, keeping its settings, and take the
/// `hosts` an older build wrote out of the config file, which is otherwise
/// left byte for byte as the owner wrote it.
pub fn write_hosts(config: &Path, hosts: &[HostConfig]) -> Result<()> {
    let mut file = read_hosts_file(config).unwrap_or_default();
    file.hosts = hosts.to_vec();
    write_hosts_file(config, &file)?;
    migrate_hosts_out(config)
}

pub fn write_hosts_file(config: &Path, file: &HostsFile) -> Result<()> {
    if let Some(dir) = config.parent() {
        fs::create_dir_all(dir)?;
    }
    let mut body = serde_json::to_vec_pretty(file)?;
    body.push(b'\n');
    crate::util::write_atomic(&hosts_path(config), &body)?;
    Ok(())
}

/// Drop `hosts` from an older config file now that the hosts file holds
/// them.
fn migrate_hosts_out(config: &Path) -> Result<()> {
    move_keys_out(config, &["hosts"])
}

/// Take `keys`, which an older build wrote, out of the config file. A file
/// with comments was never written by the deck, so it has none of the
/// deck's to move and is left alone; so is a file that is not JSON.
pub fn move_keys_out(config: &Path, keys: &[&str]) -> Result<()> {
    let Ok(bytes) = fs::read(config) else { return Ok(()) };
    if strip_comments(&bytes) != bytes {
        return Ok(());
    }
    let serde_json::Value::Object(mut map) = serde_json::from_slice::<serde_json::Value>(&bytes)? else {
        return Ok(());
    };
    let before = map.len();
    for key in keys {
        map.remove(*key);
    }
    if map.len() == before {
        return Ok(());
    }
    let mut body = serde_json::to_vec_pretty(&serde_json::Value::Object(map))?;
    body.push(b'\n');
    crate::util::write_atomic(config, &body)?;
    Ok(())
}

/// JSON with comments, as the config file may have them: `//` and `/* */`
/// comments outside strings become spaces (newlines kept, so a parse error
/// names the owner's line) and a comma before `}` or `]` goes.
pub fn strip_comments(text: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(text.len());
    let mut i = 0;
    let mut in_string = false;
    while i < text.len() {
        let b = text[i];
        if in_string {
            out.push(b);
            if b == b'\\' && i + 1 < text.len() {
                out.push(text[i + 1]);
                i += 2;
                continue;
            }
            if b == b'"' {
                in_string = false;
            }
            i += 1;
            continue;
        }
        match (b, text.get(i + 1)) {
            (b'"', _) => {
                in_string = true;
                out.push(b);
                i += 1;
            }
            (b'/', Some(b'/')) => {
                while i < text.len() && text[i] != b'\n' {
                    out.push(b' ');
                    i += 1;
                }
            }
            (b'/', Some(b'*')) => {
                out.extend_from_slice(b"  ");
                i += 2;
                while i < text.len() && !(text[i] == b'*' && text.get(i + 1) == Some(&b'/')) {
                    out.push(if text[i] == b'\n' { b'\n' } else { b' ' });
                    i += 1;
                }
                if i < text.len() {
                    out.extend_from_slice(b"  ");
                    i += 2;
                }
            }
            _ => {
                out.push(b);
                i += 1;
            }
        }
    }
    drop_trailing_commas(&mut out);
    out
}

/// A comma whose next significant byte (past comments already blanked) is
/// `}` or `]`.
fn drop_trailing_commas(text: &mut [u8]) {
    let mut in_string = false;
    let mut i = 0;
    while i < text.len() {
        let b = text[i];
        if in_string {
            if b == b'\\' {
                i += 2;
                continue;
            }
            if b == b'"' {
                in_string = false;
            }
        } else if b == b'"' {
            in_string = true;
        } else if b == b',' {
            let next = text[i + 1..].iter().find(|c| !c.is_ascii_whitespace());
            if matches!(next, Some(b'}' | b']')) {
                text[i] = b' ';
            }
        }
        i += 1;
    }
}

/// A host the hub drives, as `cepheus hosts install` records it.
#[derive(Debug, Clone, PartialEq, Deserialize, Serialize)]
pub struct HostConfig {
    /// Short and stable: sessions and `Create` name the host by it.
    pub name: String,
    /// How the deck heads the host's sessions; the name when unset.
    #[serde(default)]
    pub label: Option<String>,
    /// The host's number in session ids (`protocol::host_id`); never reused
    /// for another host, so a session keeps its id and its place.
    pub tag: u16,
    /// `address:port` of its peer listener, tried in order.
    pub addresses: Vec<String>,
    /// The SSH alias `hosts install` reaches it by.
    #[serde(default)]
    pub ssh: Option<String>,
    /// SHA-256 of its peer certificate, hex: the only certificate accepted.
    pub fingerprint: String,
    /// Agents, or builds and tests only.
    #[serde(default, skip_serializing_if = "HostRole::is_agents")]
    pub role: HostRole,
}

/// Agent hosts may run sessions. Build-only hosts report CPU, memory and disk without sessions, repository
/// mirrors, sign-in synchronization or branch scans.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum HostRole {
    #[default]
    Agents,
    Build,
}

impl HostRole {
    pub fn is_agents(&self) -> bool {
        *self == HostRole::Agents
    }
}

impl HostConfig {
    pub fn label(&self) -> String {
        self.label.clone().filter(|l| !l.trim().is_empty()).unwrap_or_else(|| self.name.clone())
    }

    pub fn runs_agents(&self) -> bool {
        self.role.is_agents()
    }
}

/// Whether `name` can name a host: lowercase letters, digits and `-`.
pub fn valid_host_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 32
        && name.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
        && !name.starts_with('-')
}

